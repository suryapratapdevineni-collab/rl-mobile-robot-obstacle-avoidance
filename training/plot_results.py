import csv
import os
import matplotlib.pyplot as plt


def load_log(log_path):
    """
    UPDATED: Matches the new CSV columns generated by the updated train_dqn.py
    """
    episodes, rewards, steps, collided, goals, epsilons = [], [], [], [], [], []
    with open(log_path, 'r') as f:
        reader = csv.DictReader(f)
        for row in reader:
            episodes.append(int(row['Episode']))
            rewards.append(float(row['Reward']))
            steps.append(int(row['Steps']))
            # Reads the new 'Collided' binary marker (0 or 1)
            collided.append(int(row['Collided']))
            goals.append(int(row['Goal']))
            epsilons.append(float(row['Epsilon']))
    return episodes, rewards, steps, collided, goals, epsilons


def moving_average(data, window=50):  # Increased window to 50 for a smoother 1000-ep scale
    if len(data) < window:
        return data
    result = []
    for i in range(len(data)):
        start = max(0, i - window + 1)
        result.append(sum(data[start:i+1]) / (i - start + 1))
    return result


def plot_all(log_path):
    episodes, rewards, steps, collided, goals, epsilons = load_log(log_path)

    fig, axes = plt.subplots(2, 2, figsize=(14, 9))

    # 1. Reward per episode
    axes[0, 0].plot(episodes, rewards, alpha=0.15, color='blue', label='raw')
    axes[0, 0].plot(episodes, moving_average(rewards, window=50), color='blue', label='moving avg (50)')
    axes[0, 0].set_title('Reward per Episode')
    axes[0, 0].set_xlabel('Episode')
    axes[0, 0].set_ylabel('Total Reward')
    axes[0, 0].legend()
    axes[0, 0].axhline(0, color='gray', linewidth=0.8, linestyle='--')

    # 2. Collision Rate (Rolling % of episodes ending in a crash)
    rolling_collision_rate = [val * 100 for val in moving_average(collided, window=50)]
    axes[0, 1].plot(episodes, rolling_collision_rate, color='red')
    axes[0, 1].set_title('Collision Rate (Rolling 50-Ep Avg %)')
    axes[0, 1].set_xlabel('Episode')
    axes[0, 1].set_ylabel('Episodes Ending in Crash (%)')
    axes[0, 1].set_ylim(-5, 105)

    # 3. Goal success rate (Rolling %)
    success_rate = [val * 100 for val in moving_average(goals, window=50)]
    axes[1, 0].plot(episodes, success_rate, color='green')
    axes[1, 0].axhline(80, color='black', linewidth=1.0, linestyle='--', label='80% target')
    axes[1, 0].set_title('Goal Success Rate (Rolling 50-Ep Avg %)')
    axes[1, 0].set_xlabel('Episode')
    axes[1, 0].set_ylabel('Success Rate (%)')
    axes[1, 0].set_ylim(-5, 105)
    axes[1, 0].legend()

    # 4. Steps per episode (Time to finish or crash)
    axes[1, 1].plot(episodes, steps, alpha=0.15, color='purple', label='raw')
    axes[1, 1].plot(episodes, moving_average(steps, window=50), color='indigo', label='moving avg (50)')
    axes[1, 1].set_title('Steps per Episode')
    axes[1, 1].set_xlabel('Episode')
    axes[1, 1].set_ylabel('Steps spent')
    axes[1, 1].legend()

    plt.tight_layout()

    out_path = os.path.join(os.path.dirname(log_path), 'training_plots.png')
    plt.savefig(out_path, dpi=150)
    print(f"Saved updated plots to {out_path}")
    print(f"Total successful runs: {sum(goals)} / {len(goals)}")
    print(f"Total runs ending in collision: {sum(collided)} / {len(collided)}")

    if len(goals) >= 50:
        last_50 = goals[-50:]
        print(f"Final Success Rate (last 50 episodes): {sum(last_50)/len(last_50)*100:.1f}%")

    plt.show()


if __name__ == "__main__":
    log_path = os.path.join(os.path.dirname(__file__), '..', 'models', 'training_log.csv')
    plot_all(log_path)